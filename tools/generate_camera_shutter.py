"""Regenerate the flash PCM asset from the supplied WAV (requires FFmpeg)."""
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def render():
    # Remove only the quiet lead/tail, retaining the full mechanical click/tail.
    # FFmpeg's resampler supplies anti-alias filtering before downsampling.
    # Match the level of synthesized UI cues offline. The source is quiet and
    # has large mechanical transients: boost its body by 18 dB, then limit those
    # peaks below full scale. No gain/limiter state or extra work on the device.
    pcm = subprocess.check_output([
        'ffmpeg', '-v', 'error', '-i', str(ROOT / 'assets/sfx/camera_shutter.wav'),
        '-af', ('atrim=start=0.120:end=0.460,asetpts=PTS-STARTPTS,'
                'aformat=channel_layouts=mono,aresample=22050,volume=8,'
                'alimiter=limit=0.89:level=false:attack=1:release=10:latency=true'),
        '-ar', '22050', '-ac', '1', '-f', 's16le', '-',
    ])
    import struct
    samples = struct.unpack('<' + 'h' * (len(pcm) // 2), pcm)
    rows = ['// Generated by tools/generate_camera_shutter.py; do not edit.']
    rows += [', '.join(map(str, samples[i:i + 16])) + ','
             for i in range(0, len(samples), 16)]
    return '\n'.join(rows) + '\n'


if __name__ == '__main__':
    (ROOT / 'src/sfx/camera_shutter_pcm.inc').write_text(render(), encoding='ascii')
