"""Render short recording cues offline; requires FFmpeg. Original WAVs retained."""
from pathlib import Path
import struct
import subprocess
ROOT = Path(__file__).resolve().parents[1]

def render(name, end):
    # The source starts promptly. Drop only its silent tail, preserve the decay,
    # and match the body level to existing UI PCM without runtime DSP/decoding.
    pcm = subprocess.check_output([
        'ffmpeg', '-v', 'error', '-i', str(ROOT / f'assets/sfx/recording_{name}.wav'),
        '-af', f'atrim=end={end},asetpts=PTS-STARTPTS,aformat=channel_layouts=mono,aresample=22050,volume=1.2',
        '-ar', '22050', '-ac', '1', '-f', 's16le', '-'])
    samples = struct.unpack('<' + 'h' * (len(pcm) // 2), pcm)
    rows = ['// Generated by tools/generate_recording_sfx.py; do not edit.']
    rows += [', '.join(map(str, samples[i:i+16])) + ',' for i in range(0, len(samples), 16)]
    return '\n'.join(rows) + '\n'

if __name__ == '__main__':
    for name, end in [('start', 0.105), ('stop', 0.135)]:
        (ROOT / f'src/sfx/recording_{name}_pcm.inc').write_text(render(name, end), encoding='ascii')
